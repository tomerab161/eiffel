#!/usr/bin/env node
// Regenerates docs/architecture.md (D4) for the IMAX-kit monorepo: packages and their internal dependencies,
// domain areas with their exports, API modules with their layers, and web features with their public entry.
// Keeps the hand-written "## Recent decisions" section intact.
// Usage: node agent-kit/scripts/map.mjs [--check]   (--check fails if the file is stale)
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { loadConfig, root } from './lib.mjs'

const require = createRequire(resolve(root, 'package.json'))
const ts = require('typescript')
const config = loadConfig()
const map = config.map
const outFile = resolve(root, map.outFile)
const DECISIONS = '## Recent decisions'
const TEST_FILE = /\.(test|steps|support|spec)\.tsx?$/

const lines = ['# Architecture map', '', '_Generated by `node agent-kit/scripts/map.mjs`. Do not edit above "Recent decisions"._', '']
lines.push(...shape(), ...packagesSection(), ...domainSection(), ...modulesSection(), ...featuresSection())

const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
const decisions = previous.includes(DECISIONS) ? previous.slice(previous.indexOf(DECISIONS)) : `${DECISIONS}\n\n- (none yet)\n`
const next = `${lines.join('\n').trimEnd()}\n\n${decisions.trimEnd()}\n`

if (process.argv.includes('--check')) {
  if (previous !== next) {
    console.error(`✗ ${map.outFile} is stale. Run node agent-kit/scripts/map.mjs and commit it.`)
    process.exit(1)
  }
  console.log('✓ architecture map is current')
} else {
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, next)
  console.log(`wrote ${map.outFile}`)
}

function shape() {
  return [
    '## Shape',
    '',
    '- `packages/domain`: Zod schemas, constants and pure rules shared by both apps. Zod is its only runtime dependency.',
    '- `apps/api`: Fastify. `modules/<module>/` = routes → service → repository → db. Outer: `shared/`, `plugins/`, `config/`, `db/`.',
    '- `apps/web`: React + TanStack Router/Query. `features/<feature>/` (public entry `index.ts`). Outer: `clients/`, `components/`, `hooks/`, `types/`, `lib/`, `constants/`. `app/` wires feature entries to routes.',
    '- Rules are enforced by `.dependency-cruiser.cjs` (arch gate). See AGENTS.md → Architecture.',
    '',
  ]
}

function packagesSection() {
  const packages = map.packageDirs.flatMap((dir) =>
    subdirs(dir)
      .map((name) => join(dir, name))
      .filter((p) => existsSync(resolve(root, p, 'package.json')))
      .map((p) => ({ path: p, pkg: JSON.parse(readFileSync(resolve(root, p, 'package.json'), 'utf8')) })),
  )
  const names = new Set(packages.map((p) => p.pkg.name))
  const out = ['## Packages', '', '| package | path | depends on | purpose |', '|---|---|---|---|']
  for (const { path, pkg } of packages) {
    const deps = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).filter((d) => names.has(d))
    out.push(`| \`${pkg.name}\` | \`${path}\` | ${deps.map((d) => `\`${d}\``).join(', ') || '—'} | ${pkg.description ?? ''} |`)
  }
  return [...out, '']
}

function domainSection() {
  const out = ['## Domain areas', '']
  for (const area of subdirs(map.domainSrc)) {
    out.push(`### ${area}`, '')
    for (const f of sourceFiles(join(map.domainSrc, area))) out.push(`- \`${f}\`: ${exportsOf(join(map.domainSrc, area, f)).join(', ') || '(no exports)'}`)
    out.push(...behavior(join(map.domainSrc, area)), '')
  }
  return out.length > 2 ? out : [...out, '- (none yet)', '']
}

function modulesSection() {
  const out = ['## API modules', '']
  for (const mod of subdirs(map.apiModules)) {
    const dir = join(map.apiModules, mod)
    out.push(`### ${mod}`, '')
    for (const layer of ['routes', 'service', 'repository']) {
      const file = `${mod}.${layer}.ts`
      if (existsSync(resolve(root, dir, file))) out.push(`- ${layer}: \`${file}\` → ${exportsOf(join(dir, file)).join(', ') || '(no exports)'}`)
    }
    const other = sourceFiles(dir).filter((f) => !/\.(routes|service|repository)\.ts$/.test(f))
    if (other.length) out.push(`- other: ${other.map((f) => `\`${f}\``).join(', ')}`)
    out.push(...behavior(dir), '')
  }
  return out.length > 2 ? out : [...out, '- (none yet)', '']
}

function featuresSection() {
  const out = ['## Web features', '']
  for (const feature of subdirs(map.webFeatures)) {
    const dir = join(map.webFeatures, feature)
    const entry = ['index.ts', 'index.tsx'].find((f) => existsSync(resolve(root, dir, f)))
    out.push(`### ${feature}`, '')
    out.push(`- public entry: ${entry ? `\`${entry}\` → ${exportsOf(join(dir, entry)).join(', ') || '(no exports)'}` : '**missing index.ts**'}`)
    const parts = subdirs(dir).filter((d) => walk(join(dir, d)).length)
    if (parts.length) out.push(`- contains: ${parts.map((d) => `\`${d}/\``).join(', ')}`)
    out.push(...behavior(dir), '')
  }
  return out.length > 2 ? out : [...out, '- (none yet)', '']
}

function behavior(dir) {
  const features = walk(dir).filter((f) => f.endsWith('.feature'))
  return features.length ? [`- behavior: ${features.map((f) => `\`${f}\``).join(', ')}`] : []
}

function subdirs(dir) {
  const abs = resolve(root, dir)
  if (!existsSync(abs)) return []
  return readdirSync(abs).filter((d) => statSync(join(abs, d)).isDirectory()).sort()
}

function sourceFiles(dir) {
  return readdirSync(resolve(root, dir)).filter((f) => /\.tsx?$/.test(f) && !TEST_FILE.test(f) && !f.startsWith('index.')).sort()
}

/** Files under dir (relative to dir), skipping dotfiles such as .gitkeep. */
function walk(dir, prefix = '') {
  const abs = resolve(root, dir, prefix)
  return readdirSync(abs)
    .filter((e) => !e.startsWith('.'))
    .sort()
    .flatMap((e) => (statSync(join(abs, e)).isDirectory() ? walk(dir, join(prefix, e)) : [join(prefix, e)]))
}

function exportsOf(file) {
  const source = ts.createSourceFile(file, readFileSync(resolve(root, file), 'utf8'), ts.ScriptTarget.Latest, true)
  const out = []
  for (const stmt of source.statements) {
    if (ts.isExportDeclaration(stmt)) {
      if (stmt.exportClause && ts.isNamedExports(stmt.exportClause)) out.push(...stmt.exportClause.elements.map((e) => `\`${e.name.getText()}\``))
      else if (stmt.moduleSpecifier) out.push(`\`* from ${stmt.moduleSpecifier.getText()}\``)
      continue
    }
    const exported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    if (!exported) continue
    if (ts.isVariableStatement(stmt)) out.push(...stmt.declarationList.declarations.map((d) => `\`${d.name.getText()}\``))
    else if (stmt.name) out.push(`\`${stmt.name.getText()}\``)
  }
  return out
}
